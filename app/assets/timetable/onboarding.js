(function(root){
  "use strict";
  const KEY="anyclass.onboardingCompleted";
  const completed=()=>{try{return localStorage.getItem(KEY)==="1"}catch(_error){return false}};
  const persist=()=>{try{localStorage.setItem(KEY,"1")}catch(_error){}};
  const dialog=()=>document.querySelector("[data-onboarding-dialog]");
  const closeDialog=node=>root.AnyClassMotion?.closeDialog?root.AnyClassMotion.closeDialog(node):Promise.resolve((node.close(),true));
  const stopBreathing=()=>dialog()?.removeAttribute("data-breathing");
  const startBreathing=node=>{stopBreathing();node.dataset.breathing="true"};
  const emptyConfirmed=()=>{const state=document.getElementById("emptyState");return Boolean(state&&!state.hidden)};
  const close=()=>{persist();stopBreathing();const node=dialog();if(node?.open)void closeDialog(node)};
  const apply=()=>{const node=dialog();if(!node)return;const shouldOpen=!completed()&&emptyConfirmed();if(shouldOpen&&!node.open){node.showModal();node.focus({preventScroll:true});requestAnimationFrame(()=>startBreathing(node))}else if(!shouldOpen&&node.open){stopBreathing();void closeDialog(node)}};
  addEventListener("DOMContentLoaded",()=>{
    const node=dialog(),state=document.getElementById("emptyState");
    if(!node||!state)return;
    new MutationObserver(apply).observe(state,{attributes:true,attributeFilter:["hidden"]});
    for(const action of node.querySelectorAll("[data-complete-onboarding]"))action.addEventListener("click",persist);
    const primary=node.querySelector("[data-onboarding-primary]");
    let pointerActivation=false;
    const markPointer=()=>{pointerActivation=true};
    primary?.addEventListener("pointerdown",markPointer,{passive:true});
    primary?.addEventListener("touchstart",markPointer,{passive:true});
    primary?.addEventListener("click",()=>{if(pointerActivation)primary.blur();pointerActivation=false});
    primary?.addEventListener("keydown",()=>{pointerActivation=false});
    node.querySelector("[data-dismiss-onboarding]")?.addEventListener("click",close);
    node.addEventListener("cancel",event=>{event.preventDefault();close()});
    node.addEventListener("click",event=>{if(event.target===node)close()});
    apply();
  });
  root.AnyClassOnboarding=Object.freeze({KEY,apply,close,complete:close,completed,stopBreathing});
})(globalThis);
